"""Backend i18n scanner (ADR-234, the Python twin of the web's TypeScript scanner): in the modules that render
generated documents, English text may not be passed directly to a document sink (TextSpan, Word/slide text calls) or
written as a Markdown heading, bullet or italic-paragraph literal; it belongs in the package's text catalog.
`# i18n-exempt` on the line marks protocol markers / developer text. Scope grows package by package
(TEMPLATE_MODULES). Also: fixed API error messages (ADR-244) and task stage codes (ADR-245) must be in the web's
tables."""

from __future__ import annotations

import ast
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RX = "plugins/report_export/src/researchos_plugin_report_export"
TEMPLATE_MODULES = [
    "services/api/researchos/services/content/export_host.py",
    "services/api/researchos/services/content/md_exporter.py",
    "services/api/researchos/services/research/deep_report.py",
    "services/api/researchos/services/writing/cards.py",
    "services/api/researchos/services/writing/methods_checklist.py",
    "services/api/researchos/services/writing/paper_card.py",
    "services/api/researchos/services/writing/feasibility.py",
    f"{RX}/slides.py",
    f"{RX}/exporters.py",
    f"{RX}/latex.py",
]
SINKS = {"TextSpan", "add_heading", "add_paragraph", "add_run", "slides_text_pages", "slide_text", "slide_lines",
         "slides_section", "table_slides", "figure_slide"}
PROTOCOL_KWARGS = {"style", "name"}  # Word style / shape names are protocol values, not text
WORDS = re.compile(r"[A-Za-z]{3,}")
MD_HEADING = re.compile(r"^(?:#{1,6} +|[-*] +|_)[A-Za-z]{3,}")  # heading, bullet or italic paragraph


def _texts(node: ast.AST) -> list[str]:
    """The literal text of a string constant or of an f-string's constant parts."""
    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        return [node.value]
    if isinstance(node, ast.JoinedStr):
        return [v.value for v in node.values if isinstance(v, ast.Constant) and isinstance(v.value, str)]
    if isinstance(node, ast.BinOp):  # "Claim: " + x
        return _texts(node.left) + _texts(node.right)
    return []


def _name(call: ast.Call) -> str:
    f = call.func
    return f.attr if isinstance(f, ast.Attribute) else f.id if isinstance(f, ast.Name) else ""


def _candidates(tree: ast.AST) -> list[tuple[ast.AST, str]]:
    """(node, text) of every sink argument with words and every Markdown heading literal."""
    out: list[tuple[ast.AST, str]] = []
    for node in ast.walk(tree):
        if isinstance(node, ast.Call) and _name(node) in SINKS:
            args = [*node.args, *(k.value for k in node.keywords if k.arg not in PROTOCOL_KWARGS)]
            out += [(a, t) for a in args for t in _texts(a) if WORDS.search(t)]
        elif isinstance(node, (ast.Constant, ast.JoinedStr)):
            out += [(node, t) for t in _texts(node) if MD_HEADING.match(t)]
    return out


def findings(source: str, path: str = "<src>") -> list[str]:
    lines = source.splitlines()
    return sorted({f"{path}:{n.lineno}: {t.strip()[:60]!r}" for n, t in _candidates(ast.parse(source))
                   if hasattr(n, "lineno") and "i18n-exempt" not in lines[n.lineno - 1]})


def test_template_modules_have_no_hard_coded_english() -> None:
    found = [f for m in TEMPLATE_MODULES for f in findings((ROOT / m).read_text(encoding="utf-8"), m)]
    assert not found, "move these strings into the package's text catalog:\n" + "\n".join(found)


def test_scanner_catches_the_patterns_it_guards() -> None:
    src = '\n'.join([
        'TextSpan("Hypothesis (pre-registered)")',
        'doc.add_heading("References", 1)',
        'slide_lines("Claim: " + str(x))',
        'TextSpan(f"Figure {i}. {name}")',
        'body.append("## Sources")',
        'out.append("- none flagged")',
        'lines.append("_Generated by the pipeline._")',
        'x = "-1 or _id"',                    # not Markdown prose: fine
        'TextSpan(f"{a} {b}: {c}")',          # data only: fine
        'TextSpan(T("metrics"))',             # catalog: fine
        'lines.append("[unresolved figure]")  # i18n-exempt',
        'slide_text(s, ["OK"])',
        'doc.add_paragraph(text, style="Caption")',  # protocol keyword: fine
    ])
    assert [f.split(": ", 1)[1] for f in findings(src)] == [
        "'Hypothesis (pre-registered)'", "'References'", "'Claim:'", "'Figure'", "'## Sources'", "'- none flagged'",
        "'_Generated by the pipeline._'"]


# ---- fixed API error messages are translated by the web (ADR-221 table; ADR-244) ----

API_ERRORS_TS = ROOT / "apps/web/src/i18n/apiErrors.ts"
FIXED_ROW = re.compile(r'\["([a-z_]+)", "((?:[^"\\]|\\.)*)", "[A-Za-z]+"\]')


def fixed_api_errors() -> dict[tuple[str, str], str]:
    """(code, exact message) -> location of every ApiError / not_found / conflict raised with literal text."""
    out: dict[tuple[str, str], str] = {}
    for f in sorted((ROOT / "services/api/researchos").rglob("*.py")):
        for n in ast.walk(ast.parse(f.read_text(encoding="utf-8"))):
            if not isinstance(n, ast.Call):
                continue
            name, a = _name(n), n.args
            lit = [x.value if isinstance(x, ast.Constant) and isinstance(x.value, str) else None for x in a]
            where = f"{f.relative_to(ROOT)}:{n.lineno}"
            if name == "ApiError" and len(a) >= 3 and lit[1] and lit[2]:
                out[(lit[1], lit[2])] = where
            elif name == "not_found" and a and lit[0]:
                out[("not_found", f"{lit[0]} not found")] = where
            elif name == "conflict" and len(a) >= 2 and lit[0] and lit[1]:
                out[(lit[0], lit[1])] = where
    return out


def test_every_fixed_api_error_message_is_in_the_web_table() -> None:
    """A new fixed message must get a row in apps/web/src/i18n/apiErrors.ts (+ both locales, checked by vitest);
    a changed backend text would otherwise silently fall back to English in the zh UI."""
    table = set(FIXED_ROW.findall(API_ERRORS_TS.read_text(encoding="utf-8")))
    found = fixed_api_errors()
    assert len(found) > 50  # the scan itself works
    missing = [f"{where}: {code} {msg!r}" for (code, msg), where in sorted(found.items()) if (code, msg) not in table]
    assert not missing, "add these to apiErrors.ts FIXED and both locales:\n" + "\n".join(missing)


# ---- task stage codes are translated by the web (ADR-245) ----

STAGE_SOURCES = ["services/api/researchos", "workers", "plugins"]
MONITOR_DEFAULT_STAGES = {"running"}  # execution/monitor.py: a run's progress record without a stage


def task_stage_codes() -> dict[str, str]:
    """Literal first arguments of `.progress("<stage>", ...)` in the host, the worker and the merged plugins."""
    out: dict[str, str] = {}
    for base in STAGE_SOURCES:
        for f in sorted((ROOT / base).rglob("*.py")):
            if "tests" in f.relative_to(ROOT).parts:
                continue
            for n in ast.walk(ast.parse(f.read_text(encoding="utf-8"))):
                if isinstance(n, ast.Call) and _name(n) == "progress" and n.args:
                    for t in _texts(n.args[0]) if isinstance(n.args[0], ast.Constant) else []:
                        out.setdefault(t, f"{f.relative_to(ROOT)}:{n.lineno}")
    return out


def test_every_task_stage_code_is_translated_by_the_web() -> None:
    locales = {loc: json.loads((ROOT / f"apps/web/src/i18n/locales/{loc}.json").read_text(encoding="utf-8"))
               for loc in ("en", "zh-CN")}
    codes = {**task_stage_codes(), **{c: "monitor default" for c in MONITOR_DEFAULT_STAGES}}
    assert "parsing" in codes and "fit" in codes  # the scan itself works
    for loc, data in locales.items():
        missing = [f"{where}: {code}" for code, where in sorted(codes.items()) if code not in data["taskStages"]]
        assert not missing, f"add to {loc}.json taskStages:\n" + "\n".join(missing)


# ---- core gate diagnostic codes are translated by the web (ADR-247) ----

GATES = ROOT / "services/api/researchos/services/writing/gates.py"
EVIDENCE_FAILURES = {"missing", "stale"}  # gates.py: add(f"evidence_{v.status}") for these VerifyStatus values


def gate_codes() -> set[str]:
    codes = {f"evidence_{s}" for s in EVIDENCE_FAILURES}
    for n in ast.walk(ast.parse(GATES.read_text(encoding="utf-8"))):
        if isinstance(n, ast.Call) and _name(n) in ("add", "Diagnostic"):
            i = 0 if _name(n) == "add" else 1
            if len(n.args) > i and isinstance(n.args[i], ast.Constant) and isinstance(n.args[i].value, str):
                codes.add(n.args[i].value)
    return codes


def test_every_core_gate_code_is_translated_by_the_web() -> None:
    codes = gate_codes()
    assert {"free_number", "unresolved_citation", "metric_unverified"} <= codes  # the scan itself works
    for loc in ("en", "zh-CN"):
        table = json.loads((ROOT / f"apps/web/src/i18n/locales/{loc}.json").read_text(encoding="utf-8"))
        missing = sorted(codes - set(table["gateDiagnostics"]))
        assert not missing, f"add to {loc}.json gateDiagnostics: {missing}"


# ---- other protocol codes the web shows as labels (M8) ----

def test_core_doc_kinds_and_answer_sentence_kinds_are_translated_by_the_web() -> None:
    from researchos.services.content.docs import CORE_DOC_KINDS
    from researchos.services.research.qa_validate import KINDS

    groups = {"docKinds": {s.name for s in CORE_DOC_KINDS}, "sentenceKinds": set(KINDS)}
    for loc in ("en", "zh-CN"):
        data = json.loads((ROOT / f"apps/web/src/i18n/locales/{loc}.json").read_text(encoding="utf-8"))
        for group, codes in groups.items():
            missing = sorted(codes - set(data[group]))
            assert not missing, f"add to {loc}.json {group}: {missing}"
