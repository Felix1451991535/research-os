"""Deep research report (K8 Doc kind `report`). Every sentence carries its Evidence placeholders
(`{{evidence:<id>}}`) and the citekeys of the works they come from (`{{cite:<key>}}`), so M6 export gates can
resolve them; numbers in method sections come from the logs (PRISMA), never from a model."""

from __future__ import annotations

import sqlite3
from typing import Any

from ...kernel.db import jload, row, tx
from ..content import docs
from ..literature import citekeys, screening
from . import claims


def _answer_section(conn: sqlite3.Connection, i: int, a: dict[str, Any]) -> list[str]:
    ans = row(conn.execute("SELECT status, body, trust_composition FROM answers WHERE id=?", (a["answer_id"],))) or {}
    body = jload(ans.get("body")) or {}
    out = [f"## {i + 1}. {a['sub_question']}", ""]
    sents = [s for s in body.get("sentences") or [] if s.get("evidence_ids")]
    if not sents:
        out += ["Insufficient material: no page-cited evidence in the imported full texts answers this.", ""]
        return out
    for s in sents:
        out.append(f"- {citekeys.cited_markdown(conn, s['text'], list(s['evidence_ids']))} *({s.get('kind')})*")
    dropped = len(body.get("dropped") or [])
    trust = ", ".join(f"{k} {_n(v)}" for k, v in (jload(ans.get("trust_composition")) or {}).items())
    out += ["", f"_Trust: {trust}; {_n(dropped)} unsupported sentence(s) removed by the deterministic and independent "
                "checks._", ""]
    return out


def _n(v: Any) -> str:
    """Values computed by the system from its own logs at generation time (not model/author numbers): marked as
    literals for the M6 number gate."""
    return f"{{{{lit:{v}}}}}"


def _prisma(p: dict[str, Any]) -> list[str]:
    by_src = ", ".join(f"{k} {_n(v)}" for k, v in p["identified_by_source"].items())
    reasons = ", ".join(f"{k} {_n(v)}" for k, v in p["excluded_reasons"].items())
    return ["## Method (PRISMA-style, from the logs)", "",
            f"- Records identified: {_n(p['records_identified'])} (by source: {by_src}); duplicates "
            f"removed: {_n(p['duplicates_removed'])}",
            f"- Screened (title/abstract, owner decisions): {_n(p['records_screened'])}; excluded: "
            f"{_n(p['records_excluded'])} ({reasons})",
            "- Full text: every included record with an open-licensed PDF was read by the pipeline; full-text "
            "screening decisions by the owner were not part of this run.",
            "- Rule/model screening outputs were suggestions only; inclusion was decided by the owner.", ""]


def _contradictions(conn: sqlite3.Connection, claim_ids: list[str], flags: dict[str, Any]) -> list[str]:
    out = ["## Possible contradictions (model suggestions, need owner review)", ""]
    pairs = claims.contradictions(conn, claim_ids)
    by_id = {c["id"]: c for c in claims.get_many(conn, claim_ids)}
    for p in pairs:
        a, b = by_id.get(p["src"]), by_id.get(p["dst"])
        if a and b:
            out.append(f"- **{p['attrs'].get('aspect')}** ({p['attrs'].get('status')}): \"{a['data']['text']}\" vs "
                       f"\"{b['data']['text']}\"")
    if not pairs:
        out.append(f"- none flagged{'' if not flags.get('error') else ' (check not run: ' + flags['error'] + ')'}"
                   f"{'' if not flags.get('note') else ' (' + flags['note'] + ')'}")
    return [*out, ""]


def _sources(conn: sqlite3.Connection, works: list[str]) -> list[str]:
    out = ["## Sources", ""]
    for w in works:
        r = row(conn.execute("SELECT title, year, retraction FROM works WHERE id=?", (w,))) or {}
        full = row(conn.execute("SELECT 1 FROM document_versions WHERE work_id=? AND parse_state IN "
                                "('parsed','partial')", (w,)))
        ret = (jload(r.get("retraction")) or {}).get("retracted")
        title = _n(str(r.get("title") or "").replace("{", "(").replace("}", ")"))
        out.append(f"- {{{{cite:{citekeys.assign(conn, w)}}}}} {title} ({_n(r.get('year') or 'n.d.')})"
                   f"{' — RETRACTED' if ret else ''}{'' if full else ' — metadata only (no full text; not cited)'}")
    return [*out, ""]


def write(conn: sqlite3.Connection, svc: Any, r: dict[str, Any], actor: str) -> dict[str, Any]:
    d = r["data"]
    lines = [f"# Deep research: {r['question']}", "",
             "_Generated by the deep research pipeline. Statements are limited to page-cited evidence from imported "
             "full texts; nothing comes from abstracts or model memory._", ""]
    lines += _prisma(screening.prisma(conn, r["review_id"]))
    for i, a in enumerate(d.get("answers") or []):
        lines += _answer_section(conn, i, a)
    lines += _contradictions(conn, d.get("claims") or [], d.get("contradictions") or {})
    lines += _sources(conn, d.get("works") or [])
    lines += ["## Limitations", "", "- Seeds of discovery are the configured sources only; grey literature and "
              "non-indexed work are missing.", "- Claims inherit the trust of their evidence; OCR is not used.", ""]
    with tx(conn):
        return docs.create_in_tx(conn, svc.doc_kinds, r["project_id"], "report", f"Deep research: {r['question']}",
                                 "\n".join(lines), actor)
