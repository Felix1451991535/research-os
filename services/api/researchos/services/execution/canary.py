"""Canary sweep (ARCHITECTURE §6.7): a tiny built-in sweep in which every run injects one known fault; the sweep
passes only if exactly the expected detector fires for each fault (and nothing fails for the clean run).

Runs go through the normal path (K3 approval of the two canary plans, K2 tasks, K5 executor, K9 detectors), on a
generated synthetic dataset. D06 (host suspend) needs a fake clock and is covered by unit tests, not here.
"""

from __future__ import annotations

import hashlib
import json
import sqlite3
from pathlib import Path
from typing import Any

from ...contracts.errors import ApiError, not_found
from ...kernel.db import jdump, jload, new_id, row, rows, tx, utcnow
from ...kernel.events import emit
from ..orchestration import tasks as task_svc
from ..orchestration.registry import KindRegistry
from . import datasets, plans
from .templates import TemplateRegistry

# mode -> (plan, expected failing detector or None for the clean run)
EXPECTED: dict[str, tuple[str, str | None]] = {
    "ok": ("group", None),
    "nan": ("group", "nonfinite"),
    "diverge": ("group", "divergence"),
    "hang": ("group", "stall"),
    "misreport": ("group", "metric_recompute"),
    "read_test": ("group", "sample_provenance"),
    "resplit": ("group", "sample_provenance"),
    "crash": ("group", "exit_solver"),
    "random_split": ("leak", "split_integrity"),
}
GROUP_SPLIT = {
    "kind": "group_counts",
    "seed": 1,
    "counts": {"train": 6, "search_val": 2, "confirm_val": 2},
    "test": ["s10", "s11"],
}
LEAK_SPLIT = {"kind": "random_rows", "seed": 3, "train_fraction": 0.8}


def make_dataset(out: Path, subjects: int = 12, seed: int = 0) -> Path:
    """Synthetic HAR-like signals, 8-sample windows with 50% overlap (a random-row split leaks half-windows)."""
    import numpy as np

    rng = np.random.default_rng(seed)
    x, y, g, ids = [], [], [], []
    for s in range(subjects):
        for c in range(3):
            sig = rng.normal(c * 1.5, 0.6, size=(40, 3)).astype("float32")
            for start in range(0, 33, 4):
                x.append(sig[start : start + 8])
                y.append(c)
                g.append(f"s{s:02d}")
                ids.append(f"s{s:02d}-c{c}-w{start}")
    out.mkdir(parents=True, exist_ok=True)
    np.savez(out / "data.npz", X=np.stack(x), y=np.array(y), group=np.array(g), sample_id=np.array(ids))
    sha = hashlib.sha256((out / "data.npz").read_bytes()).hexdigest()
    man = {
        "name": "canary_synthetic",
        "version": "1",
        "source": "generated by Research OS canary sweep",
        "license": "CC0 (synthetic)",
        "group_key": "subject",
        "overlapping_windows": True,
        "table": "data.npz",
        "files": [{"path": "data.npz", "sha256": sha}],
    }
    (out / "manifest.json").write_text(json.dumps(man), encoding="utf-8")
    return out


def _content(tpl_hash: str, ds: dict[str, Any], split: dict[str, Any], modes: list[str]) -> dict[str, Any]:
    c: dict[str, Any] = {
        "hypothesis": "each injected fault is caught by its detector; the clean run passes",
        "template": {"id": "canary", "hash": tpl_hash},
        "dataset": {"id": ds["id"], "manifest_sha256": ds["manifest_sha256"]},
        "split": split,
        "metrics": ["macro_f1"],
        "limits": {"max_minutes": 2, "stall_s": 3},
        "params": {},
        "space": {"mode": {"choices": modes}},
    }
    return c


def _modes(plan: str) -> list[str]:
    return ["ok"] if plan == "leak" else [m for m, (p, _) in EXPECTED.items() if p == plan]


def prepare(conn: sqlite3.Connection, data_dir: Path, templates: TemplateRegistry, actor: str) -> dict[str, Any]:
    """Creates the dataset and two canary plans. The owner approves both plans (normal K3) before `start`."""
    tpl = templates.get("canary")
    if tpl is None or tpl.status != "reviewed":
        raise ApiError(409, "canary_unavailable", "built-in canary template missing or not reviewed")
    ds = datasets.register(conn, make_dataset(data_dir / "canary" / "dataset"), actor)
    ids = {
        k: plans.create(conn, title=f"canary ({k} split)", content=_content(tpl.hash, ds, s, _modes(k)), actor=actor)[
            "plan_id"
        ]
        for k, s in (("group", GROUP_SPLIT), ("leak", LEAK_SPLIT))
    }
    cid = new_id("canary")
    with tx(conn):
        conn.execute(
            "INSERT INTO canaries(id,plans,template_hash,created_at) VALUES (?,?,?,?)",
            (cid, jdump(ids), tpl.hash, utcnow()),
        )
        emit(conn, "canary.prepared", actor=actor, entity_type="canary", entity_id=cid, data=ids)
    return {
        "id": cid,
        "plans": ids,
        "approve": [{"subject_type": "plan", "subject_id": f"{p}@1"} for p in ids.values()],
    }


def _get(conn: sqlite3.Connection, cid: str) -> dict[str, Any]:
    c = row(conn.execute("SELECT * FROM canaries WHERE id=?", (cid,)))
    if c is None:
        raise not_found("canary")
    return {**c, "plans": jload(c["plans"])}


def start(conn: sqlite3.Connection, kinds: KindRegistry, cid: str, actor: str) -> dict[str, Any]:
    c = _get(conn, cid)
    if any(plans.approval_covers(conn, p, 1) is None for p in c["plans"].values()):
        raise ApiError(409, "plan_not_approved", "approve both canary plans first")
    for mode, (plan, _) in EXPECTED.items():
        params = {"mode": "ok" if mode == "random_split" else mode}
        task_svc.create(
            conn,
            kinds,
            kind="experiment.run",
            actor=actor,
            idempotency_key=f"canary:{cid}:{mode}",
            payload={"plan_id": c["plans"][plan], "revision": 1, "stage": "trial", "params": params, "seed": 0},
        )
    with tx(conn):
        conn.execute("UPDATE canaries SET started_at=? WHERE id=? AND started_at IS NULL", (utcnow(), cid))
    return status(conn, cid)


def _fired(conn: sqlite3.Connection, run_id: str | None) -> list[str]:
    if run_id is None:
        return []
    sig = rows(conn.execute("SELECT detector FROM health_signals WHERE run_id=? AND severity='fail'", (run_id,)))
    return sorted({s["detector"].split("@")[0] for s in sig})


def status(conn: sqlite3.Connection, cid: str) -> dict[str, Any]:
    """Per fault: expected detector, detectors that fired (fail severity), pass/fail/pending."""
    _get(conn, cid)
    out = []
    for mode, (_, want) in EXPECTED.items():
        t = row(conn.execute("SELECT id, state FROM tasks WHERE idempotency_key=?", (f"canary:{cid}:{mode}",)))
        r = (
            row(conn.execute("SELECT id FROM runs WHERE task_id=? ORDER BY attempt DESC LIMIT 1", (t["id"],)))
            if t
            else None
        )
        fired = _fired(conn, r["id"] if r else None)
        done = t is not None and t["state"] in ("succeeded", "failed", "cancelled")
        ok = (t is not None and t["state"] == "succeeded" and not fired) if want is None else want in fired
        out.append(
            {
                "mode": mode,
                "expected": want,
                "fired": fired,
                "task_state": t["state"] if t else None,
                "result": "pending" if not done else ("pass" if ok else "fail"),
            }
        )
    results = {o["result"] for o in out}
    overall = "pending" if "pending" in results else ("pass" if results == {"pass"} else "fail")
    return {
        "id": cid,
        "overall": overall,
        "faults": out,
        "not_covered": ["host_suspend (D06): fake-clock unit test only"],
    }
